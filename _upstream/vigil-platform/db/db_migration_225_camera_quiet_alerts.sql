-- ── สถานะเหตุการณ์ "กล้องนี้กำลังเงียบอยู่" ──────────────────────────
-- มีแถวเฉพาะกล้องที่กำลังเงียบ · ลบทิ้งเมื่อกลับมาส่งข้อมูล
CREATE TABLE IF NOT EXISTS camera_quiet_alerts (
  camera_id     TEXT PRIMARY KEY,
  quiet_since   TIMESTAMPTZ,      -- ข้อมูลมาถึงครั้งสุดท้ายเมื่อไหร่ (ไม่ใช่เวลาที่เราตรวจเจอ)
  notified_at   TIMESTAMPTZ,
  notify_count  INTEGER NOT NULL DEFAULT 0,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── นิสัยของกล้องแต่ละตัว — คำนวณใหม่ทุกคืน ──────────────────────────
-- 🔴 เหตุผลที่ต้องมี (เจ้าของถามตรง ๆ 2026-09-12: "จะรู้ได้ไงว่าตัวไหนควรยกเว้น
-- ในอนาคต ถ้ามีกล้องเพิ่มอีก") — รายชื่อยกเว้นที่คนมาไล่ใส่เองคือหนี้ที่โตทุกครั้ง
-- ที่ติดกล้องเพิ่ม และไม่มีใครกลับมารื้อ · ให้ตัวเลขของกล้องเองเป็นคนตอบแทน
--
-- p99_min = "ปกติแล้วกล้องตัวนี้เงียบนานสุดกี่นาที โดยตัด 1% ที่แปลกที่สุดทิ้ง"
-- ⚠️ ต้องเป็น p99 ไม่ใช่ max: ของ C9-KAR ค่า max คือ 530 นาที ซึ่ง **คือเหตุการณ์
--    ที่เรากำลังจะจับนั่นเอง** ⇒ ใช้ max = เหตุการณ์กลายเป็นนิสัยปกติของกล้องทันที
--    ส่วน p99 ขยับไม่ได้เพราะเหตุการณ์เป็น 1 ใน 1,905 ตัวอย่าง (0.05%)
--
-- วัดจริง 7 วัน (274,359 ช่อง) — ตัวเลขที่ทำให้กฎนี้ใช้ได้:
--   C9/C10/C17-KAR  p99 =     5 นาที  → เฝ้าได้ · วันเกิดเหตุเงียบ 530 นาที = 100 เท่า
--   HDY-NVR-01-ch0  p99 =    93 นาที  → กล้อง Face ที่ประตู เงียบชั่วโมงครึ่งเป็นเรื่องปกติ
--   DAHUA_CAM01     p99 = 1,066 นาที  → เงียบเกือบวันเป็นเรื่องปกติ
--   HDY-NVR-04-ch1  p99 = 1,509 นาที  → เฝ้าไม่ได้ ความเงียบคือสภาพปกติของมัน
-- ทดสอบกฎกับของจริง: 4 กล้องที่ควรเตือน เตือนครบ 4/4 ·
--                     11 กล้องที่ไม่ควรเตือน ถูกยกเว้นอัตโนมัติครบ 11/11
-- ครอบคลุม 128/169 กล้อง (76%) โดยไม่ต้องมีใครมาตั้งค่าให้ทีละตัว
CREATE TABLE IF NOT EXISTS camera_event_baseline (
  camera_id    TEXT PRIMARY KEY,
  p99_min      INTEGER NOT NULL,   -- นาที
  samples      INTEGER NOT NULL,   -- จำนวนช่องว่างที่ใช้คำนวณ (น้อย = ยังเชื่อไม่ได้)
  days_span    NUMERIC(4,1),       -- ข้อมูลกินเวลากี่วัน (กล้องติดใหม่จะต่ำ)
  computed_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ตั้งค่าของตัวเตือน — แยกจาก edge_alert เพราะผู้รับคนละกลุ่มกัน:
-- edge ล่ม = เรื่องของทีมเรา · กล้องเงียบรายตัว = อาจเป็นกลุ่มลูกค้า/ตำรวจ
-- ⇒ ห้ามใช้สวิตช์ร่วมกัน ไม่งั้นเปิดอันหนึ่งแล้วอีกอันหลุดตามไปด้วย
--
-- 🔴 `enabled` คุม **เฉพาะการยิง LINE** ไม่ได้คุมการคำนวณสถานะ — สถานะถูกคำนวณ
-- ลง camera_quiet_alerts เสมอ เพื่อให้หน้าจอมีตัวเลขอ่านได้ตั้งแต่ยังไม่เปิด LINE
-- (เจ้าของสั่ง 2026-09-12: ยังไม่ได้กำหนดกลุ่มผู้รับ ถ้าหลุดเข้ากลุ่มลูกค้าจะยุ่ง)
--
-- เกณฑ์ของกล้องแต่ละตัว = max(floor_min, multiplier × p99_min)
-- เฝ้าเฉพาะกล้องที่ p99_min ≤ baseline_ceiling_min และ samples ≥ min_samples
ALTER TABLE line_config
  ADD COLUMN IF NOT EXISTS quiet_alert JSONB NOT NULL
  DEFAULT '{"enabled":false,"floor_min":20,"multiplier":3,"baseline_ceiling_min":30,"min_samples":100,"cooldown_hours":6,"excluded_cameras":[],"recipient_ids":[]}'::jsonb;

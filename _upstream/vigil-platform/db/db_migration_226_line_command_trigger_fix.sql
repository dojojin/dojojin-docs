-- คำสั่งจับผิดสองครั้งจริงบน prod (ยืนยันจาก line_command_log ไม่ใช่เดา):
--
--   1. "...แจ้งเตือนย้อนหลัง เดี๋ยวผมไปปิดแจ้งเตือนย้อนหลังก่อน" → คำว่า "ปิดแจ้งเตือน"
--      ชนคำเรียกของ mute_plate ตรงตัว (คะแนน 12, ไม่ใช่การเดา) ⇒ บอทถาม "ป้ายทะเบียน
--      อะไร" ทั้งที่ผู้พิมพ์กำลังพูดเรื่องปิดฟีเจอร์แจ้งเตือนย้อนหลัง คนละเรื่องกับป้าย
--   2. "คุยกับพี่วิรุธ แล้ว @Wirut Boonrit" → คำว่า "แล้ว" (คำไทยสามัญมาก) เป็นส่วนหนึ่ง
--      ของคำเรียก "เห็นแล้ว" (ack_alert) ⇒ ทาง suggest() เสนอ "รับทราบการแจ้งเตือน"
--
-- ตรวจก่อนตัด (2026-09-14): ack_alert ไม่เคยถูกใช้สำเร็จเลยสักครั้งในปูมทั้งหมด —
-- ตัด "เห็นแล้ว" ไม่มีต้นทุน · ส่วน mute_plate วิธีพิมพ์จริงตามเอกสาร/เทสต์คือ
-- "หยุดแจ้งเตือน 1กอ88 3 ชั่วโมง" ไม่เคยมีคำว่า "ปิดแจ้งเตือน" เลย ตัดออกไม่กระทบ
-- การใช้งานจริง คำเรียกที่เหลือ (หยุดแจ้งเตือน/พักแจ้งเตือน/งดแจ้งเตือน/ปิดเสียง)
-- เฉพาะเจาะจงพอที่จะไม่ชนกับ "ปิดแจ้งเตือน<เรื่องอื่น>" แบบเดิม
--
-- ทางเลือกที่พิจารณาแล้วไม่เลือก: บังคับต้อง @ บอทก่อนสั่งเสมอ — พลิกการตัดสินใจ
-- เดิม (2026-09-08, เอกสาร docs/LOGIC_line-commands.md §3) ที่ตั้งใจให้พิมพ์ประโยค
-- ไทยธรรมดาได้โดยไม่ต้องจำ syntax และวัดอัตราจริง 14 วันแล้วพบว่าบทสนทนาไม่เกี่ยวข้อง
-- ที่ชนคำสั่งจริงมีแค่ 1 ครั้งจาก 162 ข้อความ — ไม่คุ้มที่จะเปลี่ยน UX ของทุกคน

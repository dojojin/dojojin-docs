UPDATE line_commands
   SET triggers = triggers - 'เห็นแล้ว'
 WHERE action_key = 'ack_alert'
   AND triggers ? 'เห็นแล้ว';

UPDATE line_commands
   SET triggers = triggers - 'ปิดแจ้งเตือน'
 WHERE action_key = 'mute_plate'
   AND triggers ? 'ปิดแจ้งเตือน';

-- ทั้งไซต์เป็นศูนย์ติดกัน 5 วันโดยไม่มีอะไรร้องเลย กว่าจะรู้คือ 8 วันให้หลัง และรู้
-- เพราะเจ้าของสังเกตด้วยตาเปล่า ไม่ใช่เพราะระบบบอก
--
-- 🔴 ตั้งต้น enabled=false และ recipient_ids=[] เหมือน quiet_alert ไม่ใช่ edge_alert
--    เหตุผลเดียวกัน (เจ้าของสั่ง 2026-09-12): ผู้รับ LINE ที่เปิดอยู่ตอนนี้รวมกลุ่ม
--    ลูกค้าและตำรวจ · ตัวเตือนที่ fallback เป็น "ทุกคน" จะยิงเข้ากลุ่มลูกค้าทันที
--    ที่ใครเปิดสวิตช์ ⇒ ต้องระบุกลุ่มผู้รับเองเสมอ
--
-- เกณฑ์มาจากการวัด 30 วันจริง ไม่ใช่เดา — ความแกว่งของอัตรารายวันต่างกันมากตามไซต์
--   hkt     median 85.4% sd 0.67 (ต่ำสุด 84.0 สูงสุด 87.2)
--   hdy     median 57.7% sd 4.88 (ต่ำสุด 36.7 สูงสุด 69.2)
--   rmutr-v median 67.8% sd 8.02 (ต่ำสุด 51.3 สูงสุด 81.7)
-- ⇒ เกณฑ์ตายตัวเป็นจุดเปอร์เซ็นต์ใช้ไม่ได้ ("ตก 15 จุด" เงียบกับ hkt แต่ปลุกผิด
--   กับ hdy ที่แกว่ง 21 จุดเป็นเรื่องปกติ) จึงอิงการแกว่งของไซต์ตัวเอง:
--   เส้นเตือน = median - max(sd_k x sd, min_margin_pp)
--   ด้วยค่าตั้งต้น sd_k=5 min_margin_pp=10 ได้เส้น hkt 75.4 · hdy 33.3 · rmutr-v 27.7
--   ทั้งสามเส้นอยู่ต่ำกว่าค่าต่ำสุดที่เคยวัดได้จริงของไซต์นั้น ๆ (ไม่ปลุกผิด)
--   และสูงกว่าศูนย์มาก (จับเคสภูเก็ตได้ตั้งแต่วันแรกแทนที่จะเป็นวันที่ 8)
-- ============================================================

ALTER TABLE line_config
  ADD COLUMN IF NOT EXISTS metric_alert JSONB NOT NULL
  DEFAULT '{"enabled": false, "recipient_ids": [], "sd_k": 5, "min_margin_pp": 10,
            "baseline_days": 14, "min_baseline_days": 7, "min_rows_per_day": 200,
            "cooldown_hours": 24}'::jsonb;

COMMENT ON COLUMN line_config.metric_alert IS
  'เตือนเมื่ออัตรา "พร้อมข้อมูลทะเบียน" ของไซต์ตกต่ำกว่าการแกว่งปกติของไซต์นั้นเอง (RCA 2026-09-18 ข้อ 8.3) ตั้งต้นปิด และไม่มีผู้รับ';

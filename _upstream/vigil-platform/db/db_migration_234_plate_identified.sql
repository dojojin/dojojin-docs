ALTER TABLE cameras
  ADD COLUMN IF NOT EXISTS plate_conf_floor REAL;

COMMENT ON COLUMN cameras.plate_conf_floor IS
  'เส้นแบ่ง confidence ของการอ่านป้าย (ค่าคงที่ต่อกล้อง ตั้งตามสเกลของรุ่นนั้น) NULL = ไม่กรอง';

-- ผลที่ตรึงไว้ตอนบันทึก · NULL = ยังไม่ถูกตัดสิน (แถวเก่าก่อน backfill)
-- ห้ามอ่านคอลัมน์นี้ในเส้นทางที่ผู้ใช้เห็น จนกว่า backfill จะจบ ไม่งั้นแถวที่ยัง
-- เป็น NULL จะถูกนับเป็น "ไม่ผ่าน" ทั้งที่แค่ยังไม่ได้ตัดสิน

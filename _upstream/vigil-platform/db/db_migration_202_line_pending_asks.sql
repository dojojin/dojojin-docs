-- เก็บคำถามที่ค้างไว้ใน **ตาราง ไม่ใช่หน่วยความจำ** เพราะ api-server ถูก restart
-- บ่อยกว่าที่คิด (วันนี้วันเดียว 10 ครั้ง) ถ้าเก็บใน Map คำถามที่ค้างจะหายกลางคัน
-- แล้วผู้ใช้ที่เพิ่งตอบ "ภูเก็ต" จะได้ความเงียบกลับไปโดยไม่รู้ว่าเกิดอะไรขึ้น
--
-- หนึ่งคำถามค้างต่อ (คน × ห้อง) — ถามใหม่ทับของเดิมเสมอ ไม่สะสมคิว
-- ============================================================

CREATE TABLE IF NOT EXISTS line_pending_asks (
  line_user_id text NOT NULL,
  source_id    text NOT NULL,          -- ห้องที่ถาม (กลุ่ม/ห้อง/แชทส่วนตัว)
  command_key  text NOT NULL,
  slots        jsonb NOT NULL DEFAULT '{}'::jsonb,   -- ที่เก็บได้แล้ว รอเติมที่ขาด
  need         text NOT NULL,          -- ช่องที่กำลังรอคำตอบ: site | period | choice
  options      jsonb NOT NULL DEFAULT '[]'::jsonb,   -- ตัวเลือกที่เสนอไป (ตอบเป็นเลขได้)
  asked_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (line_user_id, source_id)
);

-- คำถามค้างที่เก่ากว่า 2 นาที = คนละบทสนทนาแล้ว (ตัวรันเช็คเวลาเองด้วย
-- ดัชนีนี้ไว้ให้การกวาดทิ้งเป็นระยะไม่ต้อง seq scan)
CREATE INDEX IF NOT EXISTS idx_line_pending_asked ON line_pending_asks (asked_at);

-- ช่องที่ "ต้องมี" ของแต่ละคำสั่ง — ขาดเมื่อไหร่บอทถามกลับแทนที่จะเดา
-- ค่าว่าง = ไม่บังคับอะไรเลย (พฤติกรรมเดิมของคำสั่งที่สร้างไว้ก่อนหน้านี้)
ALTER TABLE line_commands ADD COLUMN IF NOT EXISTS required_slots jsonb NOT NULL DEFAULT '[]'::jsonb;

-- ยอดผู้ไม่สวมหมวกนิรภัย = ตัวที่เจ้าของยกมาเป็นตัวอย่างว่าต้องถามไซต์
-- (คำสั่งอันดับป้ายไม่บังคับ — คำถามแบบ "ป้ายไหนบ่อยสุด" ถามข้ามไซต์ก็มีความหมาย)
UPDATE line_commands SET required_slots = '["site"]'::jsonb, updated_at = now()
 WHERE key = 'helmet_count' AND required_slots = '[]'::jsonb;

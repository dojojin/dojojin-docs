-- เจ้าของถาม 2026-09-08: "ขอยอดผู้ไม่สวมหมวกนิรภัย ภูเก็ต เฉพาะกล้อง หน้าโรงเรียนนาบอน (C20)"
-- ก่อนหน้านี้ชื่อกล้องถูกมองข้ามทั้งดุ้น แล้วบอทตอบยอดของทั้งไซต์ 86 กล้องกลับไป
-- ตัวเลขดูน่าเชื่อแต่ตอบคนละคำถาม — เป็นความล้มเหลวแบบที่แย่ที่สุดเพราะไม่มีอะไรบอกว่าผิด
--
-- ไม่บังคับ (ไม่อยู่ใน required_slots) — ถามยอดทั้งไซต์ยังเป็นคำถามที่มีความหมาย
-- ระบุกล้องเมื่อไหร่ กล้องชนะไซต์เสมอเพราะแคบกว่า
-- ============================================================

UPDATE line_commands
   SET slots = (slots::jsonb || '["camera"]'::jsonb), updated_at = now()
 WHERE key IN ('helmet_count', 'lpr_count')
   AND NOT (slots @> '["camera"]'::jsonb);

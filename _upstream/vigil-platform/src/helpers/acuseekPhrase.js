/**
 * แปลงคำบอกเวลาหนึ่งจุดเป็น "นาทีนับจากเที่ยงคืน" · คืน null เมื่ออ่านไม่ออก
 * รองรับทั้ง 14:00 / 14.00 / 14 น. และภาษาพูด
 */
function parseClock(text) {
  const t = norm(text).replace(/\s+/g, '');
  if (!t) return null;

  // ── รูปแบบตัวเลขล้วน — 14:00 · 14.30 · 14 น.
  let m = t.match(/(\d{1,2})[:.](\d{2})/);
  if (m) { const h = +m[1], mi = +m[2]; if (h < 24 && mi < 60) return h * 60 + mi; }
  m = t.match(/^(\d{1,2})น\.?$/);
  if (m && +m[1] < 24) return +m[1] * 60;

  // ── นาทีต่อท้าย: "ครึ่ง" = 30 · "ทุ่ม45" = 45
  const halfRe = /ครึ่ง/;
  const minRe = new RegExp(`(?:โมง|ทุ่ม|ตี|เที่ยง)\\s*(\\d{1,2})(?!\\d)`);

  const pick = (base) => {
    if (base == null) return null;
    let mi = 0;
    if (halfRe.test(t)) mi = 30;
    else { const mm = t.match(minRe); if (mm && +mm[1] < 60) mi = +mm[1]; }
    return base * 60 + mi;
  };

  if (/เที่ยงคืน/.test(t)) return pick(0);
  if (/เที่ยง/.test(t)) return pick(12);

  // ตี N → N (ตี 1–5)
  m = t.match(new RegExp(`ตี${_NUM_RE}`));
  if (m) { const n = _num(m[1]); if (n != null && n >= 1 && n <= 5) return pick(n); }

  // N ทุ่ม → N+18 · "ทุ่ม" เดี่ยว ๆ = 1 ทุ่ม
  m = t.match(new RegExp(`${_NUM_RE}ทุ่ม`));
  if (m) { const n = _num(m[1]); if (n != null && n >= 1 && n <= 5) return pick(18 + n); }
  if (/ทุ่ม/.test(t)) return pick(19);

  // บ่าย N โมง → N+12 · "บ่ายโมง" เดี่ยว ๆ = 13:00
  m = t.match(new RegExp(`บ่าย${_NUM_RE}?โมง`));
  if (m) { const n = _num(m[1]); return pick(12 + (n == null ? 1 : n)); }

  // N โมงเย็น → N+12
  m = t.match(new RegExp(`${_NUM_RE}โมงเย็น`));
  if (m) { const n = _num(m[1]); if (n != null && n >= 1 && n <= 7) return pick(12 + n); }

  // N โมง(เช้า) → ดูหมายเหตุเรื่องสองระบบด้านบน
  m = t.match(new RegExp(`${_NUM_RE}โมง`));
  if (m) {
    const n = _num(m[1]);
    if (n != null && n >= 1 && n <= 11) return pick(n >= 6 ? n : n + 6);
  }
  return null;
}

/**
 * หาช่วงเวลาแบบ "ตั้งแต่ X ถึง Y" จากข้อความ
 * คืน { fromMin, toMin, label } · null เมื่อไม่พบช่วง
 * ถ้าพบเวลาเดียว → ถือเป็นช่วงหนึ่งชั่วโมงนับจากเวลานั้น
 */
function parseTimeRange(text) {
  const t = norm(text);
  const sep = t.split(/\s*(?:ถึง|-|–|—|ระหว่าง|จนถึง|ต่อ)\s*/);
  if (sep.length >= 2) {
    for (let i = 0; i < sep.length - 1; i++) {
      const a = parseClock(sep[i]), b = parseClock(sep[i + 1]);
      if (a != null && b != null && a !== b) {
        return { fromMin: a, toMin: b, label: `${_hhmm(a)}–${_hhmm(b)}` };
      }
    }
  }
  // ── เส้นแบ่งระหว่าง "ชื่อช่วง" กับ "เวลาจุดเดียว" ────────────────────────
  // ตัดสินจาก **ตัวบอกเวลาชัดเจน** (โมง · ทุ่ม · ตี · ตัวเลข) ไม่ใช่จากการมีชื่อช่วง
  //
  //   "ก่อนเที่ยง"  ไม่มีตัวบอกเวลา → ชื่อช่วง 10:00–12:00 ✓
  //   "บ่ายโมง"     มี "โมง"        → เวลาจุด 13:00 ✓
  //   "ตอนบ่าย"     ไม่มี           → ชื่อช่วง 12:00–18:00 ✓
  //   "ทุ่มครึ่ง"    มี "ทุ่ม"       → เวลาจุด 19:30 ✓
  //
  // เคยตัดสินจาก "มีชื่อช่วงไหม" อย่างเดียว ผลคือ "บ่ายโมง" ถูกกลืนเป็นช่วงบ่ายทั้งยวง
  // 12:00–18:00 แล้วผลค้นออกมาเป็นห้าโมงเย็น (เจ้าของจับได้จากภาพผลลัพธ์ 2026-08-12)
  if (!_CLOCK_MARK.test(t) && TIME_WORDS.some((w) => w.re.test(t))) return null;
  const one = parseClock(t);
  if (one != null) return { fromMin: one, toMin: (one + 60) % 1440, label: `${_hhmm(one)}–${_hhmm((one + 60) % 1440)}` };
  return null;
}

// ตัวบอกเวลาชัดเจน — ถ้ามีตัวใดตัวหนึ่ง ถือว่าผู้ใช้ระบุ "เวลา" ไม่ใช่ "ช่วงของวัน"
const _CLOCK_MARK = /โมง|ทุ่ม|ตี\s*(?:\d|หนึ่ง|สอง|สาม|สี่|ห้า)|\d{1,2}[:.]\d{2}|\d{1,2}\s*น\.?|เที่ยงตรง/;

const _hhmm = (min) => `${String(Math.floor(min / 60) % 24).padStart(2, '0')}:${String(min % 60).padStart(2, '0')}`;

// ── วันที่เจาะจง ─────────────────────────────────────────────────────────
// "วันที่ 10 สิงหา" · "10 ส.ค." · "10/8" · "10/8/2569" · "2026-08-10"
// ปี พ.ศ. แปลงให้เอง (2569 → 2026) — คนไทยพิมพ์ พ.ศ. เป็นปกติ ถ้าไม่แปลงจะได้ปี 2569
// ซึ่งอยู่นอกช่วงที่เครื่องรับ (2004–2037) แล้วค้นไม่เจออะไรเลยโดยไม่มีอะไรบอกว่าทำไม
const THAI_MONTH = {
  'มกรา': 1, 'ม.ค': 1, 'มค': 1,
  'กุมภา': 2, 'ก.พ': 2, 'กพ': 2,
  'มีนา': 3, 'มี.ค': 3, 'มีค': 3,
  'เมษา': 4, 'เม.ย': 4, 'เมย': 4,
  'พฤษภา': 5, 'พ.ค': 5, 'พค': 5,
  'มิถุนา': 6, 'มิ.ย': 6, 'มิย': 6,
  'กรกฎา': 7, 'ก.ค': 7, 'กค': 7,
  'สิงหา': 8, 'ส.ค': 8, 'สค': 8,
  'กันยา': 9, 'ก.ย': 9, 'กย': 9,
  'ตุลา': 10, 'ต.ค': 10, 'ตค': 10,
  'พฤศจิกา': 11, 'พ.ย': 11, 'พย': 11,
  'ธันวา': 12, 'ธ.ค': 12, 'ธค': 12,
};

/** ปี พ.ศ. → ค.ศ. · เลข 2 หลักถือเป็น พ.ศ. ย่อ (69 → 2569 → 2026) */
function _year(n) {
  let y = Number(n);
  if (!Number.isFinite(y)) return null;
  if (y < 100) y += y > 50 ? 2500 : 2000;     // 69 → 2569 · 26 → 2026
  if (y >= 2400) y -= 543;                     // พ.ศ. → ค.ศ.
  return (y >= 2004 && y <= 2037) ? y : null;  // ช่วงที่เครื่องรับ
}

/**
 * หาวันที่เจาะจงในข้อความ · คืน { y, m, d, label } หรือ null
 * ไม่ระบุปี = ปีปัจจุบัน · ระบุวันที่ในอนาคต = ถือว่าหมายถึงปีก่อน
 */
function parseDate(text, nowMs) {
  const t = norm(text);
  const now = nowMs ? new Date(nowMs) : new Date();
  let y = null, m = null, d = null;

  // 2026-08-10
  let mm = t.match(/(\d{4})-(\d{1,2})-(\d{1,2})/);
  if (mm) { y = _year(mm[1]); m = +mm[2]; d = +mm[3]; }

  // 10/8 · 10/8/2569 · 10-8-69
  if (m == null) {
    mm = t.match(/(?:วันที่\s*)?(\d{1,2})[/](\d{1,2})(?:[/](\d{2,4}))?/);
    if (mm) { d = +mm[1]; m = +mm[2]; y = mm[3] ? _year(mm[3]) : null; }
  }

  // วันที่ 10 สิงหา (2569) — ชื่อเดือนไทย
  if (m == null) {
    for (const [name, num] of Object.entries(THAI_MONTH)) {
      const re = new RegExp(`(?:วันที่\\s*)?(\\d{1,2})\\s*${name.replace('.', '\\.')}\\.?\\s*(\\d{2,4})?`);
      const g = t.match(re);
      if (g) { d = +g[1]; m = num; y = g[2] ? _year(g[2]) : null; break; }
    }
  }

  if (m == null || d == null || m < 1 || m > 12 || d < 1 || d > 31) return null;
  if (y == null) {
    y = now.getFullYear();
    // ระบุวันที่ที่ยังไม่มาถึงในปีนี้ = หมายถึงปีที่แล้ว (คนพูดถึงอดีตเสมอเมื่อค้นวิดีโอ)
    const cand = new Date(Date.UTC(y, m - 1, d));
    if (cand.getTime() > now.getTime() + 864e5) y -= 1;
  }
  return { y, m, d, label: `${String(d).padStart(2, '0')}/${String(m).padStart(2, '0')}/${y}` };
}

/**
 * จับคำบอกเวลาจากข้อความไทย
 * คืน { band, days, range, label, words[] } · เป็น null เมื่อไม่พบ (ผู้เรียกใช้ค่าจากฟอร์ม)
 * `range` = ช่วงเวลาที่ระบุเป็นนาที ซึ่งละเอียดกว่า `band` และมีสิทธิ์ก่อน
 */
function parseTime(text) {
  const t = norm(text);
  const words = [];
  let band = null, dayOffset = null, daysBack = null;

  // วันที่เจาะจงต้องหาก่อน parseTimeRange — ไม่งั้น "10/8" จะถูกอ่านเป็นช่วงเวลา 10:00
  const date = parseDate(t);
  // ตัดวันที่ออกจากข้อความก่อนหาช่วงเวลา กัน "2026-08-10" กลายเป็นเวลา
  const tNoDate = date ? t.replace(/\d{4}-\d{1,2}-\d{1,2}|(?:วันที่\s*)?\d{1,2}[/]\d{1,2}(?:[/]\d{2,4})?/g, ' ') : t;

  // ช่วงเวลาที่ระบุเป็นตัวเลข/ภาษาพูด มาก่อนคำกว้าง ๆ อย่าง "กลางวัน" เสมอ
  // เพราะละเอียดกว่าและเป็นสิ่งที่ผู้ใช้ตั้งใจระบุ
  const range = parseTimeRange(tNoDate);

  const tw = TIME_WORDS.find((w) => w.re.test(tNoDate));
  if (tw) { band = tw.band; if (tw.day != null) dayOffset = tw.day; words.push(BANDS[tw.band].th); }

  const dw = DAY_WORDS.find((w) => w.re.test(t));
  if (dw) {
    if (dw.offset != null) dayOffset = dw.offset; else daysBack = dw.back;
    words.push(dw.th);
  }

  if (!range && !date && band === null && dayOffset === null && daysBack === null) {
    return { band: null, days: null, dayOffset: null, range: null, date: null, label: null, words: [] };
  }
  const label = [date ? date.label : (dw ? dw.th : null),
                 range ? range.label : (tw ? BANDS[tw.band].th : null)]
    .filter(Boolean).join(' · ');
  if (range) words.push(range.label);
  if (date) words.push(date.label);
  // `days` เก็บไว้เพื่อความเข้ากันได้ = จำนวนวันที่จะค้น (เจาะจงวันเดียว = 1)
  return { band, days: dayOffset != null ? 1 : daysBack, dayOffset, range, date, label, words };
}

/** ชั่วโมงเริ่ม-จบของช่วง · คืน null เมื่อเป็นทั้งวัน (ไม่ต้องซอย) */
function bandHours(band) {
  const b = BANDS[band];
  if (!b || band === 'all') return null;
  return { from: b.from, to: b.to, th: b.th };
}


/** หาคำต้องห้ามในข้อความ (ตรวจทั้งคำไทยและคำอังกฤษที่ผู้ใช้อาจพิมพ์มาเอง) */
function findBlocked(text) {
  const t = norm(text).toLowerCase();
  const hits = [];
  for (const b of BLOCKED) {
    const thHit = b.th.find((w) => t.includes(w.toLowerCase()));
    const enHit = t.includes(b.en.toLowerCase()) ? b.en : null;
    if (thHit || enHit) hits.push({ word: thHit || enHit, en: b.en, group: b.group, hint: BLOCKED_HINT[b.en] || null });
  }
  return hits;
}

/**
 * หารูปคำถามที่เครื่องตอบไม่ได้ — ตรวจ **ทั้งข้อความไทยที่ผู้ใช้พิมพ์ และวลีอังกฤษ
 * ที่จะถูกส่งไปให้เครื่องจริง**
 *
 * 🔴 ทำไมต้องตรวจฝั่งอังกฤษด้วย: AcuSeek เป็นระบบ embedding — มันไม่มีคำว่า "ไม่รู้"
 * ถามอะไรไปก็คืนเพื่อนบ้านที่ใกล้ที่สุดพร้อมคะแนนสวยเสมอ ("คนถือปืน" ได้ 97 โดยใน
 * ภาพทั้ง 3 ใบไม่มีปืน) · ด่านนี้จึงเป็นสิ่งเดียวที่กันผู้ใช้จากการเชื่อผลที่ผิด
 *
 * ตราบใดที่ regex เป็นภาษาไทยล้วน วลีอังกฤษที่มาจากทางอื่น — วันนี้คือช่องที่ผู้ใช้
 * พิมพ์อังกฤษเองได้ พรุ่งนี้คือตัวแปลภาษา — จะเดินผ่านด่านนี้ไปเงียบ ๆ
 * ตัวแปลที่ผลิต `a person smoking a cigarette` จากคำที่ regex ไทยไม่ตรง คือกรณีที่
 * ระบบจะ **แย่ลงกว่าเดิม** เพราะผู้ใช้ได้ผล 95 ที่ดูน่าเชื่อแต่ผิด
 *
 * @param {string} text     ข้อความไทยที่ผู้ใช้พิมพ์
 * @param {string} [english] วลีอังกฤษที่จะส่งไปให้เครื่อง (ถ้ามี)
 */
function findUnsupported(text, english) {
  const t = norm(text);
  const e = norm(english);
  const seen = new Set();
  const out = [];
  for (const u of UNSUPPORTED) {
    // ฝั่งไทยตรวจก่อนเสมอ เพื่อให้ id ไม่ซ้ำเมื่อทั้งสองฝั่งจับได้อันเดียวกัน
    const hit = u.re.test(t) || (e && u.en && u.en.test(e));
    if (!hit || seen.has(u.id)) continue;
    seen.add(u.id);
    out.push({ id: u.id, th: u.th, why: u.why, proof: u.proof });
  }
  return out;
}

/**
 * แปลไทย → วลีอังกฤษที่ AcuSeek เข้าใจ
 * คืน null เมื่อไม่รู้จักคำใดเลย (ผู้เรียกจะบอกผู้ใช้ให้พิมพ์ใหม่ ไม่ใช่ส่งขยะไปให้เครื่อง)
 */
/**
 * แปลจริง + รายงานว่า "อ่านคำนี้ออกแต่ไม่ได้ใช้" ตรงไหนบ้าง
 *
 * 🔴 ทำไมต้องรายงานแยกจาก unknownWords: unknownWords ตอบได้แค่ "ไม่รู้จักคำ"
 * ซึ่งจับได้เฉพาะคำนอกตาราง · ความพังที่อันตรายกว่าคือคำที่อยู่ในตารางแล้ว
 * อ่านออกแล้ว แต่ตอนประกอบประโยคกลับตกหล่น ⇒ unknown ว่าง ไม่มีคำเตือนใด ๆ
 * ทั้งที่คำค้นเพี้ยนไปคนละเรื่อง ("คนจูงหมา" → `a dog`, คนหายทั้งคน)
 *
 * ที่นี่ **ไม่แก้ผลการแปล** — แก้ตรรกะประกอบประโยคเป็นงานคนละก้อน (ลำดับใน HEAD
 * เลือกตัวแรกในตาราง ไม่ใช่ประธานจริง) · หน้าที่ของฟังก์ชันนี้คือทำให้ความพัง
 * **มองเห็น** เท่านั้น เพราะผู้ใช้แก้ประโยคอังกฤษเองได้อยู่แล้วถ้ารู้ว่าต้องแก้
 */
function translate(text) {
  const t = norm(text);
  if (!t) return { english: null, dropped: [] };

  const head = HEAD.find((h) => h.re.test(t));
  // ประธานตัวที่สองที่เป็นคน — เดิมหายไปเงียบ ๆ เพราะ HEAD.find() เอาแค่ตัวแรก
  // "ผู้ชายเดินจับมือผู้หญิง" เคยกลายเป็น "a man walking" เฉย ๆ (เจ้าของจับได้)
  const second = head && head.kind === 'person'
    ? HEAD.find((h) => h.kind === 'person' && h !== head && h.re.test(t))
    : null;
  const pair = PAIR.find((x) => x.re.test(t));
  // ช่องละอันเดียว — กันวลีที่ขัดแย้งกันเอง (ดูหมายเหตุที่ WORN)
  const seen = new Set();
  const worn = [];
  for (const w of WORN) {
    if (seen.has(w.slot) || !w.re.test(t)) continue;
    seen.add(w.slot); worn.push(w.en);
  }
  const act = ACTION.find((a) => a.re.test(t));
  const color = COLOR.find(([re]) => re.test(t));

  if (!head && !worn.length && !act && !pair) return { english: null, dropped: [] };

  // ประธาน: ถ้าไม่ระบุว่าคนหรือรถ แต่มีของสวมใส่/ท่าทาง → ถือว่าเป็นคน
  let subject = head ? head.en : 'a person';
  let kind = head ? head.kind : 'person';

  // 🔑 "คนขี่มอเตอร์ไซค์" = **คน** ไม่ใช่รถ · รูปที่พิสูจน์แล้วว่าได้ผล 3/3 คือ
  // `a motorcycle rider without a helmet` ไม่ใช่ `a motorcycle without a helmet`
  // เงื่อนไข: เป็นยานพาหนะ + มีคำว่าขี่/ซ้อน หรือมีของสวมใส่ (ซึ่งเป็นของคน ไม่ใช่ของรถ)
  const ridden = /ขี่|ซ้อน|คนขับ|ผู้ขับ|ไรเดอร์/.test(t);
  if (kind === 'vehicle' && (ridden || worn.length)) {
    subject = `${subject.replace(/^(a|an) /, '')} rider`;
    subject = /^[aeiou]/i.test(subject) ? `an ${subject}` : `a ${subject}`;
    kind = 'person';
  }

  // สีของยานพาหนะเติมเข้าไปในประธานตรง ๆ · สีของเสื้อผ้าเป็นวลีต่อท้าย
  const parts = [];
  if (color && kind === 'vehicle') {
    subject = subject.replace(/^(a|an) /, `$1 ${color[1]} `)
                     .replace(/^a ([aeiou])/, 'an $1');
  } else if (color) {
    // "เสื้อยืดขาวกางเกงยีนส์" — สีขาวต้องไปกับเสื้อ ไม่ใช่กางเกง
    // ตัดสินจากคำเสื้อผ้าที่อยู่ **ใกล้คำสีที่สุด** ไม่ใช่แค่ว่ามีคำว่ากางเกงอยู่ในประโยคไหม
    // ภาษาไทยวางสีไว้ **หลัง** สิ่งที่ถูกขยาย ("เสื้อยืดขาว" · "กางเกงขาสั้นสีดำ")
    // จึงหาคำเสื้อผ้าตัวสุดท้ายที่อยู่ก่อนคำสี ไม่ใช่ตัวที่ใกล้ที่สุดสองทาง
    const ci = t.search(color[0]);
    const lastBefore = (re) => {
      let last = -1;
      for (const m of t.matchAll(new RegExp(re.source, 'g'))) { if (m.index < ci) last = m.index; }
      return last;
    };
    const legs = lastBefore(/กางเกง|ขาสั้น|ขายาว|ยีนส์|กระโปรง/);
    const top  = lastBefore(/เสื้อ/);
    if (legs >= 0 || top >= 0) {
      parts.push(legs > top ? `wearing ${color[1]} trousers` : `wearing a ${color[1]} shirt`);
    }
    // ไม่มีคำเสื้อผ้ามาก่อนสีเลย = สีนั้นขยายอย่างอื่น (เช่น "ร่มสีแดง") ซึ่งเรายังไม่รู้จัก
    // ⇒ ไม่แต่งเป็นเสื้อให้ · unknownWords จะรายงานให้ผู้ใช้เห็นเองว่ามีคำที่ตกไป
  }

  // คนคู่: "a man with a woman holding hands together" — รูปที่ทดสอบแล้วได้ผลจริง
  // ข้ามประธานที่สองเมื่อวลีคู่พูดถึงอยู่แล้ว ("อุ้มเด็ก" ไม่ต้องได้ "with a child" ซ้ำ)
  if (second && !(pair && pair.en.includes(second.en.replace(/^an? /, '')))) {
    subject += ` with ${second.en}`;
  }
  parts.push(...worn);
  // "riding" ซ้ำซ้อนเมื่อประธานเป็น "... rider" อยู่แล้ว · และท่าทางไม่ใช้กับสิ่งของ
  if (act && kind !== 'thing' && !(act.en === 'riding' && /rider$/.test(subject))
      && !(pair && pair.en.includes(act.en))) parts.push(act.en);
  if (pair) parts.push(pair.en);

  // ประกอบเป็นวลี ไม่ใช่คำเดี่ยว — วัดแล้วว่าวลีได้คะแนนดีกว่าคำเดี่ยวชัดเจน
  const english = parts.length
    ? `${subject} ${parts.join(' ')}`.replace(/\s+/g, ' ').trim()
    : subject;

  // ── ตรวจว่าอะไร "อ่านออกแต่ไม่ได้ใช้" ────────────────────────────────
  const lower   = english.toLowerCase();
  const dropped = [];

  // 1. ประโยคมีคำว่าคน/ผู้ชาย/ผู้หญิง แต่ประธานที่ได้ไม่ใช่คน
  //    เกิดจาก HEAD.find() คืน "ตัวแรกในตาราง" ซึ่ง หมา/แมว/รถเข็น อยู่เหนือคน
  const personHead = HEAD.find((h) => h.kind === 'person' && h.re.test(t));
  if (personHead && kind !== 'person') {
    dropped.push({
      why: 'person',
      th:  t.match(personHead.re)?.[0] || 'คน',
      note: `คำค้นพูดถึง “คน” แต่สิ่งที่ส่งไปค้นคือ “${english}” — คนหายไปจากประโยค`,
    });
  }

  // 2. สีที่อ่านออกแต่ไม่ได้ติดไปกับประโยค (สีจะถูกใช้ต่อเมื่อมีคำเสื้อผ้านำหน้า
  //    หรือประธานเป็นยานพาหนะ · "หมวกกันน็อคสีขาว" จึงทิ้งขาวเงียบ ๆ)
  //    วนทุกสี ไม่ใช่แค่สีแรก เพราะ COLOR.find() หยิบได้ทีละอัน ⇒ สีที่สองหายเสมอ
  for (const [re, en] of COLOR) {
    if (!re.test(t) || lower.includes(en)) continue;
    dropped.push({
      why: 'color',
      th:  t.match(re)?.[0] || en,
      note: `สี “${t.match(re)?.[0] || en}” ไม่ได้ถูกส่งไปค้น — ระบบผูกสีเข้ากับเสื้อผ้าหรือรถเท่านั้น`,
    });
  }

  // 3. ยุบเหลือประธานเปล่า ๆ = ค้นกว้างกว่าที่ผู้ใช้ขอมาก
  //    (prepare() จะตัดข้อนี้ทิ้งถ้ามีคำเตือนอื่นอยู่แล้ว ไม่ให้เตือนซ้ำซ้อน)
  //
  // เทียบกับ "ประธานดิบ" ไม่ใช่ parts.length เปล่า ๆ — สีของยานพาหนะถูกยัดเข้าไป
  // **ในประธาน** ("a white pickup truck") ทำให้ parts ว่างทั้งที่ประโยคครบแล้ว
  // เช็คด้วย parts.length เฉย ๆ จะเตือน "รถกระบะสีขาว" ผิด ๆ (เทสต์จับได้ตอนเขียน)
  const bare = head ? head.en : 'a person';
  if (english === bare) {
    dropped.push({
      why: 'collapse',
      th:  english,
      note: `เหลือแค่ “${english}” — รายละเอียดที่พิมพ์มาไม่ได้ถูกส่งไปค้นเลย ผลจะกว้างมาก`,
    });
  }

  return { english, dropped };
}

/** คงรูปเดิมไว้ให้ที่อื่นเรียกได้เหมือนเดิม */
function toEnglish(text) {
  return translate(text).english;
}

// คำเชื่อม/คำช่วยที่ไม่มีความหมายต่อการค้น — ไม่ต้องเตือนว่าแปลไม่ออก
const FILLER = /^(ที่|ของ|และ|กับ|หรือ|ตอน|เมื่อ|ใน|บน|ให้|เป็น|อยู่|มา|ไป|กัน|ๆ|คน|นี้|นั้น|ช่วง|วัน|เวลา|หา|ดู|ขอ|ครับ|ค่ะ|หน่อย|ด้วย|แล้ว|จะ|ได้|ก็|ทั้ง|ทุก|ใส่|สวม|มี|ถือ|บนเสื้อ|ใส่เสื้อ|สี|ตัว|อัน|ชิ้น|กำลัง|ผู้|ท่าน|ราย)$/;

/**
 * คำในข้อความที่ระบบ **ไม่รู้จัก** — ตัวที่หลุดไปจะหายเงียบ ๆ จากคำค้น
 *
 * 🔴 เหตุผลที่ต้องมี: "ผู้ชายเดินจับมือผู้หญิง" เคยกลายเป็น "a man walking" เฉย ๆ
 * คำว่า "จับมือ" กับ "ผู้หญิง" หายไปโดยไม่มีอะไรบอก ผู้ใช้จึงไม่รู้ว่าต้องแก้ประโยค
 * อังกฤษเอง (เจ้าของเจอเอง 2026-08-12) · การเติมคำในตารางแก้ได้ทีละคำ แต่การ
 * **บอกว่าคำไหนหลุด** แก้ได้ทั้งคลาส เพราะผู้ใช้เห็นเองแล้วแก้ที่ช่องภาษาอังกฤษได้
 */
function unknownWords(text) {
  const t = norm(text);
  const used = new Array(t.length).fill(false);
  const mark = (re) => {
    const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
    for (const m of t.matchAll(g)) for (let i = m.index; i < m.index + m[0].length; i++) used[i] = true;
  };
  for (const list of [HEAD, WORN, ACTION, PAIR, UNSUPPORTED, TIME_WORDS, DAY_WORDS])
    for (const r of list) mark(r.re);
  for (const [re] of COLOR) mark(re);
  for (const b of BLOCKED) for (const w of b.th) mark(new RegExp(w));
  // เวลา/วันที่ที่อ่านออกแล้ว ไม่ใช่คำที่ไม่รู้จัก
  mark(/\d[\d:.\/-]*|โมง|ทุ่ม|ตี|เที่ยง|ครึ่ง|น\.|ถึง|วันที่|ย้อน|เช้า|สาย|บ่าย|เย็น|ค่ำ|ดึก|มืด/);
  mark(/เสื้อ|กางเกง|กระโปรง|ชุด/);   // คำเสื้อผ้าที่ตรรกะสีอ่านอยู่แล้ว

  const out = [];
  let cur = '';
  for (let i = 0; i <= t.length; i++) {
    const c = t[i];
    if (i < t.length && !used[i] && /[\u0E00-\u0E7Fa-zA-Z]/.test(c)) { cur += c; continue; }
    // ลอกคำช่วยที่ติดมาในก้อนออกก่อน — ไทยไม่เว้นวรรค คำเหลือจึงมักเป็นก้อนปนกัน
    const stripped = cur.replace(/ใส่|สวม|กำลัง|ที่|ของ|และ|กับ|มี|ถือ|เป็น|อยู่|คน|ผู้|สี|ตัว|บน|ใน/g, '');
    if (stripped.length >= 2 && !FILLER.test(stripped)) out.push(cur);
    cur = '';
  }
  return [...new Set(out)];
}

/**
 * ตัวหลักที่ route เรียก — คืนทุกอย่างที่หน้าจอต้องใช้ในครั้งเดียว
 * { ok, english, blocked[], warnings[], unknown[], dropped[] }
 * ok=false เมื่อมีคำต้องห้าม หรือแปลไม่ออก · warnings/dropped ไม่ทำให้ ok=false
 *
 * unknown = ไม่รู้จักคำ · dropped = รู้จักแล้วแต่ไม่ได้ใช้ — คนละอาการ ต้องแยกกัน
 */
function prepare(text) {
  const blocked = findBlocked(text);
  const time = parseTime(text);          // คำบอกเวลาไม่กระทบ ok — เป็นข้อมูลเสริม
  const unknown = unknownWords(text);    // คำที่หลุดจากการแปล — ต้องบอกผู้ใช้เสมอ
  // ถูกบล็อกแล้วไม่มีวลีอังกฤษให้ตรวจ — เตือนจากฝั่งไทยอย่างเดียวพอ
  if (blocked.length) {
    return { ok: false, reason: 'blocked', english: null, blocked,
             warnings: findUnsupported(text), time, unknown, dropped: [] };
  }
  const { english, dropped } = translate(text);
  if (!english) {
    return { ok: false, reason: 'unknown', english: null, blocked,
             warnings: findUnsupported(text), time, unknown, dropped: [] };
  }
  // "ยุบเหลือประธานเปล่า" เป็นตาข่ายกันตก — ถ้ามีคำเตือนที่เจาะจงกว่าอยู่แล้ว
  // (ไม่รู้จักคำ / คนหาย / สีหาย) การเตือนซ้ำมีแต่ทำให้คนเลิกอ่านคำเตือน
  const specific = dropped.filter((d) => d.why !== 'collapse');
  const shown = (specific.length || unknown.length) ? specific : dropped;

  // ⚠️ ต้องแปลให้เสร็จ **ก่อน** ตรวจ — ด่านนี้ต้องเห็นวลีที่จะถูกส่งไปให้เครื่องจริง
  // ไม่ใช่เห็นแค่สิ่งที่ผู้ใช้พิมพ์ · เป็นเงื่อนไขบังคับก่อนจะใส่ตัวแปลภาษาเข้ามา
  return { ok: true, english, blocked, warnings: findUnsupported(text, english),
           time, unknown, dropped: shown };
}

/** รายการให้หน้าจอเอาไปแสดงเป็นตาราง "คำที่ใช้ไม่ได้" */
function blockedTable() {
  const byGroup = {};
  for (const b of BLOCKED) (byGroup[b.group] ||= []).push(b.th[0]);
  return Object.entries(byGroup).map(([group, words]) => ({ group, words }));
}


// E2 (docs/reports/2026-09-27_mosquitto-migration-plan.md §11). Builds the
// two files edge/mosquitto.conf.template's global `password_file`/`acl_file`
// point at, from this edge's own decrypted camera map — same source
// edge-config-agent already holds for pushMqttSettings(). Written only when
// EDGE_BROKER=mosquitto; NanoMQ edges never call this.
//
// password_file/acl_file are GLOBAL (no per_listener_settings), so a client
// that sends a username is checked against them on EVERY listener, including
// loopback — `listener_allow_anonymous true` only exempts clients that send
// no username at all (verified on a throwaway broker). Some loopback
// services on real edges DO send one: edge/bridge.js's local leg and the
// snapshot-publishing ingesters connect as MQTT_SUBSCRIBER_USER /
// SNAPSHOT_PUBLISHER_USER (src/.env). Deploying the global password_file
// without also listing those accounts would cut them off even with
// EDGE_MQTT_REQUIRE_AUTH off — so `localUsers` (see localBrokerUsersFromEnv
// below) is written into both files alongside the camera accounts, with its
// own `topic readwrite #` (loopback services publish AND subscribe).
//
// ACL shape (tested against a throwaway broker, §11.1/11.2): the anonymous
// line `topic readwrite #` comes first — applies to clients that connect
// with no username. Then one `user <name>` / `topic readwrite #` block per
// local service account. Then one `user <mqtt_username>` / `topic write
// <camera_id>/#` per Bosch camera — write-only, because a full debug capture
// never showed a Bosch camera SUBSCRIBE (only PUBLISH + PINGREQ). A camera
// whose mqtt_username collides with a local service account is skipped
// (rather than silently letting one clobber the other's ACL entry).
//
// Password handling: the plaintext user:pass file is hashed in place by
// `mosquitto_passwd -U` via execFile (no shell — the password never touches
// argv/ps) and immediately deleted; only the $7$ (PBKDF2-SHA512) hash ever
// lands in mosquitto.passwd. Nothing here logs a password or returns one.
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFile: execFileCb } = require('child_process');

const HEADER = '# Generated by src/helpers/mosquittoAuthFiles.js — do not edit by hand\n';
// MQTT wildcards (+ #), the ACL user/topic delimiter (:), and any whitespace
// (including \n\r, which would otherwise inject extra ACL/passwd lines).
const BAD_TOKEN_RE = /[\s+#:]/;

function _validToken(s) {
  return typeof s === 'string' && s.length > 0 && !BAD_TOKEN_RE.test(s);
}

// Loopback service accounts that must survive the switch to a global
// password_file. Both halves of a pair have to be set — an env with just a
// username (or just a password) is a misconfiguration, not a partial account,
// so it is left out rather than guessed at. Read from `env` (caller passes
// process.env, live) rather than src/config.js's env.str() on purpose: this
// runs from scripts/ too, outside api-server's boot path.
const LOCAL_USER_ENV_PAIRS = [
  ['MQTT_SUBSCRIBER_USER', 'MQTT_SUBSCRIBER_PASSWORD'],
  ['SNAPSHOT_PUBLISHER_USER', 'SNAPSHOT_PUBLISHER_PASSWORD'],
];
function localBrokerUsersFromEnv(env) {
  const seen = new Set();
  const out = [];
  for (const [uKey, pKey] of LOCAL_USER_ENV_PAIRS) {
    const username = env && env[uKey];
    const password = env && env[pKey];
    if (!username || !password) continue;
    if (seen.has(username)) continue; // e.g. both pairs happen to share one account
    seen.add(username);
    out.push({ username, password });
  }
  return out;
}

// A pair with a username but no password is a trap, not a skip: that client
// SENDS the username, and once a password_file exists Mosquitto refuses it
// even on the anonymous loopback listener (seen on vss3 2026-09-28 —
// edge-bridge + dahua would have been cut off). Returns the offending USER keys.
function incompleteLocalUserKeys(env) {
  return LOCAL_USER_ENV_PAIRS
    .filter(([uKey, pKey]) => env && env[uKey] && !env[pKey])
    .map(([uKey]) => uKey);
}

// Validates + dedupes the local service accounts. Failures land in the same
// `skipped` shape as a camera, labeled so they're still traceable in the log.
function _validateLocalUsers(localUsers) {
  const entries = [];
  const skipped = [];
  const seen = new Set();
  for (const u of (localUsers || [])) {
    const username = u && u.username;
    const password = u && u.password;
    const label = `(local:${username || '?'})`;
    if (!_validToken(username)) { skipped.push({ camera_id: label, reason: 'local username unsafe for the ACL' }); continue; }
    if (typeof password !== 'string' || !password) { skipped.push({ camera_id: label, reason: 'local user missing a password' }); continue; }
    if (/[\r\n\0]/.test(password)) { skipped.push({ camera_id: label, reason: 'local password contains a control character' }); continue; }
    if (seen.has(username)) { skipped.push({ camera_id: label, reason: `duplicate local username '${username}'` }); continue; }
    seen.add(username);
    entries.push({ username, password });
  }
  return { entries, skipped };
}

// Same selection + validation for both the ACL and the password file, so the
// two can never drift apart on which accounts are included.
function _selectCameraCreds(cameras, localUsers) {
  const { entries: localEntries, skipped: localSkipped } = _validateLocalUsers(localUsers);
  const localUsernames = new Set(localEntries.map((e) => e.username));

  const entries = [];
  const skipped = [...localSkipped];
  const seenUsers = new Set();

  const sorted = [...(cameras || [])].sort((a, b) =>
    String(a.camera_id || '').localeCompare(String(b.camera_id || '')));

  for (const c of sorted) {
    const cameraId = c.camera_id;
    if ((c.vendor || 'bosch').toLowerCase() !== 'bosch') continue; // only Bosch publishes to camera_id/# today
    if (!cameraId) { skipped.push({ camera_id: '(no id)', reason: 'missing camera_id' }); continue; }
    const username = c.mqtt_username;
    const password = c.mqtt_password;
    if (typeof password === 'string' && password.startsWith('enc:v1:')) {
      skipped.push({ camera_id: cameraId, reason: 'password not decrypted' }); continue;
    }
    if (!username || !password) {
      skipped.push({ camera_id: cameraId, reason: 'missing mqtt_username/mqtt_password' }); continue;
    }
    if (!_validToken(cameraId)) {
      skipped.push({ camera_id: cameraId, reason: 'camera_id unsafe for an ACL topic' }); continue;
    }
    if (!_validToken(username)) {
      skipped.push({ camera_id: cameraId, reason: 'mqtt_username unsafe for the ACL' }); continue;
    }
    if (/[\r\n\0]/.test(password)) {
      skipped.push({ camera_id: cameraId, reason: 'mqtt_password contains a control character' }); continue;
    }
    if (localUsernames.has(username)) {
      skipped.push({ camera_id: cameraId, reason: 'username clashes with local service account' }); continue;
    }
    if (seenUsers.has(username)) {
      skipped.push({ camera_id: cameraId, reason: `duplicate mqtt_username '${username}'` }); continue;
    }
    seenUsers.add(username);
    entries.push({ camera_id: cameraId, username, password });
  }
  return { entries, localEntries, skipped };
}

function _aclText(entries, localEntries) {
  const lines = [HEADER.trimEnd(), 'topic readwrite #', ''];
  for (const e of (localEntries || [])) lines.push(`user ${e.username}`, 'topic readwrite #');
  for (const e of entries) lines.push(`user ${e.username}`, `topic write ${e.camera_id}/#`);
  return lines.join('\n') + '\n';
}

/** @returns {string} the ACL file content for these cameras + local service accounts */
function buildAcl(cameras, localUsers) {
  const { entries, localEntries } = _selectCameraCreds(cameras, localUsers);
  return _aclText(entries, localEntries);
}

function _execFileP(execFile, bin, args) {
  return new Promise((resolve, reject) => {
    execFile(bin, args, (err, stdout, stderr) => {
      if (err) return reject(Object.assign(err, { stderr }));
      resolve({ stdout, stderr });
    });
  });
}

/**
 * Writes mosquitto.passwd + mosquitto.acl into `dir` (atomically, 0600),
 * hashing passwords via mosquitto_passwd -U. No-ops the rewrite (but still
 * returns the current user/skip lists) when nothing has changed since the
 * last write.
 *
 * @param {object} opts
 * @param {Array<object>} opts.cameras         decrypted cameras-config.json cameras
 * @param {Array<{username,password}>} [opts.localUsers] loopback service accounts — see localBrokerUsersFromEnv
 * @param {string} opts.dir                    e.g. ~/.config/vigil
 * @param {string} [opts.passwdBin]            default 'mosquitto_passwd'
 * @param {Function} [opts.execFile]           default child_process.execFile — injectable for tests
 * @returns {Promise<{changed: boolean, users: string[], skipped: Array<{camera_id, reason}>}>}
 */
async function writeAuthFiles({ cameras, localUsers = [], dir, passwdBin = 'mosquitto_passwd', execFile = execFileCb }) {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });

  const { entries, localEntries, skipped } = _selectCameraCreds(cameras, localUsers);
  const allEntries = [...localEntries, ...entries]; // local accounts first — same order the ACL lists them in
  const users = allEntries.map((e) => e.username);
  const acl = _aclText(entries, localEntries);
  // Sorted independently of ordering so a hash only changes when the actual
  // (user,pass) set or the ACL text changes.
  const plainLines = allEntries.map((e) => `${e.username}:${e.password}`).sort();
  const hash = crypto.createHash('sha256').update(plainLines.join('\n') + '\n' + acl).digest('hex');

  const passwdPath = path.join(dir, 'mosquitto.passwd');
  const aclPath = path.join(dir, 'mosquitto.acl');
  const shaPath = path.join(dir, '.mosquitto-auth.sha256');

  let prevHash = null;
  try { prevHash = fs.readFileSync(shaPath, 'utf8').trim(); } catch { /* first run */ }
  if (prevHash === hash && fs.existsSync(passwdPath) && fs.existsSync(aclPath)) {
    return { changed: false, users, skipped };
  }

  const tmpDir = fs.mkdtempSync(path.join(dir, '.auth-'));
  try {
    fs.chmodSync(tmpDir, 0o700);
    const plainFile = path.join(tmpDir, 'passwd.plain');

    if (allEntries.length === 0) {
      // mosquitto_passwd -U on an empty file is not a case worth exercising —
      // an empty passwd file (no users, ever) is unambiguous on its own.
      fs.writeFileSync(plainFile, '', { mode: 0o600 });
    } else {
      fs.writeFileSync(plainFile, plainLines.join('\n') + '\n', { mode: 0o600 });
      await _execFileP(execFile, passwdBin, ['-U', plainFile]);
      fs.chmodSync(plainFile, 0o600); // defense in depth — -U is expected to preserve mode, don't trust it blindly
    }
    fs.renameSync(plainFile, passwdPath);

    const aclTmp = path.join(tmpDir, 'acl.tmp');
    fs.writeFileSync(aclTmp, acl, { mode: 0o600 });
    fs.renameSync(aclTmp, aclPath);

    fs.writeFileSync(shaPath, hash + '\n', { mode: 0o600 }); // last — only once both real files are in place
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }

  return { changed: true, users, skipped };
}

module.exports = { buildAcl, writeAuthFiles, localBrokerUsersFromEnv, incompleteLocalUserKeys };

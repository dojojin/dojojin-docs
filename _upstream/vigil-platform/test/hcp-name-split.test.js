// HCP มีช่องชื่อสองช่อง และเจ้าหน้าที่กรอกสลับกันไปมาจริง ๆ — สำรวจ 1,931 คน
// (2026-09-09) พบสองแบบหลักที่ตรงข้ามกันคนละทาง:
//   ช่องหน้า = ป้ายหมวด · ช่องหลัง = ชื่อคน     842 คน  ("บุคคลหน้าขาว จชต." / "นายรีซูวัน …")
//   ช่องหน้า = ชื่อคน   · ช่องหลัง = ฐานความผิด 126 คน  ("นายชาญยุทธ พาลี" / "ลักทรัพย์ …")
//   ช่องหลังว่าง ชื่อกับป้ายรวมกันช่องเดียว      811 คน
//
// ตัวตัดสินคือ **คำนำหน้าชื่ออยู่ช่องไหน** ไม่ใช่ลำดับช่อง · เคสในไฟล์นี้คือของจริง
// ทั้งหมดที่เจ้าของส่งมาให้ดู ห้ามแก้ให้ตรงกับโค้ด ต้องแก้โค้ดให้ตรงกับเคส
'use strict';

const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

// ดึงฟังก์ชันจริงจากซอร์ส — ไฟล์นั้น export เฉพาะของที่ importer ใช้
const SRC = fs.readFileSync(path.join(__dirname, '..', 'src', 'helpers', 'blacklistImport.js'), 'utf8');
const BLOCK = SRC.match(/const TITLE_RE[\s\S]*?\nfunction splitHcpName[\s\S]*?\n\}/);
assert.ok(BLOCK, 'ไม่เจอ splitHcpName ใน blacklistImport.js');
// eslint-disable-next-line no-new-func
const splitHcpName = new Function(`${BLOCK[0]}; return splitHcpName;`)();

describe('แยกชื่อคนออกจากป้ายหมวด (HCP)', () => {
  it('ช่องหลังมีคำนำหน้า = ชื่อจริงอยู่ช่องหลัง ช่องหน้าเป็นหมวด', () => {
    for (const [g, f, name, cat] of [
      ['บุคคลหน้าขาว จชต.', 'นายรีซูวัน ดือราแม', 'นายรีซูวัน ดือราแม', 'บุคคลหน้าขาว จชต.'],
      ['บุคคลสูญหาย', 'น.ส. วรินทร์พร ยั่งยืนวงศ์', 'น.ส. วรินทร์พร ยั่งยืนวงศ์', 'บุคคลสูญหาย'],
      ['ผู้ต้องหาตามหมายจับ', 'นาย ดอน จ้อยจำปา', 'นาย ดอน จ้อยจำปา', 'ผู้ต้องหาตามหมายจับ'],
    ]) assert.deepEqual(splitHcpName(g, f), { name, category: cat });
  });

  it('ช่องหน้ามีคำนำหน้า = ชื่อจริงอยู่ช่องหน้า ช่องหลังเป็นฐานความผิด', () => {
    for (const [g, f, name, cat] of [
      ['นายชาญยุทธ พาลี', 'ลักทรัพย์ในเวลากลางคืน', 'นายชาญยุทธ พาลี', 'ลักทรัพย์ในเวลากลางคืน'],
      ['นายวรุต เล่หลัง', 'จำหน่ายยาเสพติด', 'นายวรุต เล่หลัง', 'จำหน่ายยาเสพติด'],
      ['Mr.OZEIAS DA SILVA', 'ปลอมเงินตรา', 'Mr.OZEIAS DA SILVA', 'ปลอมเงินตรา'],
    ]) assert.deepEqual(splitHcpName(g, f), { name, category: cat });
  });

  it('ช่องเดียวที่ชื่อกับป้ายรวมกัน — ตัดป้ายที่รู้จักออกจากหัว', () => {
    assert.deepEqual(splitHcpName('ผู้ต้องหาตามหมายจับ นายสมชาย ใจดี', null),
      { name: 'นายสมชาย ใจดี', category: 'ผู้ต้องหาตามหมายจับ' });
    assert.deepEqual(splitHcpName(null, 'บุคคลหน้าขาว จชต. นายอาดัม ดือราแมหะยี'),
      { name: 'นายอาดัม ดือราแมหะยี', category: 'บุคคลหน้าขาว จชต.' });
  });

  // 🔴 ของเดิมต้องไม่แย่ลง: เคสที่แยกไม่ออกจริง ๆ ให้ต่อสองช่องเหมือนเดิม
  // ห้ามเดาว่าช่องไหนเป็นชื่อ เพราะเดาผิด = ชื่อคนในบัญชีดำผิดคน
  it('แยกไม่ออกจริง ๆ ต้องต่อสองช่องเหมือนพฤติกรรมเดิม ไม่ใช่เดา', () => {
    assert.deepEqual(splitHcpName('สมชาย หอมเกตุ', 'แจ้ง พ.ต.ต.ธีรศักดิ์ 0931539251'),
      { name: 'สมชาย หอมเกตุ แจ้ง พ.ต.ต.ธีรศักดิ์ 0931539251', category: null });
  });

  it('ป้ายยาวต้องชนะป้ายสั้นที่ซ้อนอยู่ข้างใน', () => {
    // "บุคคลตามหมายจับ" มีคำว่า "บุคคล" อยู่ข้างใน — ถ้าจับสั้นก่อนจะเหลือ "ตามหมายจับ …"
    assert.equal(splitHcpName('บุคคลตามหมายจับ นายเอ บีซี', null).category, 'บุคคลตามหมายจับ');
  });

  it('ช่องว่างทั้งคู่ต้องไม่ระเบิด', () => {
    assert.deepEqual(splitHcpName(null, null), { name: null, category: null });
  });
});

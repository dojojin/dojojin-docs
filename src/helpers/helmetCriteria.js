const PLATE_OK     = '^[0-9]?[ก-ฮ]{2,3}[0-9]{3,4}$';
// ใช้เฉพาะตอน seed ค่า cameras.plate_conf_floor ครั้งแรก (scripts/seed-plate-conf-floor.js)

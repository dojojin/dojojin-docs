// เราตัดสินแทนคนอ่าน · ชื่อตัวชี้วัดบอกไปแล้วว่านับเฉพาะที่มีข้อมูลทะเบียน
// เท่านั้นพอ · ที่ยังเหลือใต้เลขคือ "ข้อมูล ณ HH:MM" ซึ่งเป็นข้อเท็จจริงล้วน

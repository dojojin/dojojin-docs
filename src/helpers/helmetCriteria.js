// ---------- self-check ----------
// `node src/helpers/helmetCriteria.js`
if (require.main === module) {
  const assert = require('assert');

  // เกณฑ์ต้องเป็นการอ่านผลที่ตรึงไว้ ไม่ใช่การคำนวณใหม่
  const s = evidenceSql('lp');
  assert.strictEqual(s, ' AND lp.plate_identified', s);
  assert.ok(!s.includes('confidence'), 'ห้ามคำนวณ confidence ตอน query อีก — ตัดสินตอน INSERT แล้ว');

  // เปลี่ยน alias ต้องเปลี่ยนให้ครบ
  assert.strictEqual(evidenceSql('f'), ' AND f.plate_identified');
  // ไม่มี alias (query ที่ select จาก CTE ตรง ๆ)
  assert.strictEqual(evidenceSql(''), ' AND plate_identified');

  // ค่าที่จะเขียนตอน INSERT: กล้องที่ยังไม่ตั้งเส้นแบ่งต้องไม่ถูกกรองด้วย confidence
  const stamp = stampSql('$28', '$4', '$2');
  assert.ok(stamp.includes('COALESCE'), 'ต้อง COALESCE เป็น TRUE เมื่อกล้องยังไม่มีเส้นแบ่ง');
  assert.ok(stamp.includes('plate_conf_floor'), 'ต้องอ่านเส้นแบ่งรายกล้อง');
  assert.ok(stamp.includes('$28') && stamp.includes('$4') && stamp.includes('$2'), stamp);

  // ตัวเช็ครูปแบบป้ายฝั่ง JS ต้องให้ผลตรงกับ regex ที่ใช้ใน SQL
  assert.strictEqual(plateMatches('1กก1234'), true);
  assert.strictEqual(plateMatches('ABC123'), false);
  assert.strictEqual(plateMatches(null), false);

  // ฐานต้องเป็น 2 ล้อเท่านั้น — รถ 3 ล้อเคยหลุดเข้ามาปนในกราฟ 24 ชม.
  assert.strictEqual(baseSql('t'), "t.no_helmet AND t.vehicle_type = 'twoWheelVehicle'");

  // ป้ายทะเบียนไทยที่ใช้จริง ต้องผ่าน · ป้ายที่อ่านไม่ครบ ต้องไม่ผ่าน
  const re = new RegExp(PLATE_OK);
  for (const ok of ['1กก1234', 'กข1234', '2กจ694', 'ขจน9'.replace('ขจน9', 'ขจน999')])
    assert.ok(re.test(ok), `ควรผ่าน: ${ok}`);
  for (const bad of ['', 'ก1234', '1ก12', 'ABC123', '1กก12345'])
    assert.ok(!re.test(bad), `ไม่ควรผ่าน: ${bad}`);

  // นโยบาย cache ต้องครอบทุก period ที่หน้าจอมีปุ่มให้กด ไม่งั้นตกไปใช้ค่า default
  // แล้วสองหน้าจะกลับไปหมดอายุคนละจังหวะอีก
  for (const pd of ['hour', 'today', 'yesterday', 'week', 'month', 'custom'])
    assert.strictEqual(typeof CACHE_TTL_BY_PERIOD[pd], 'number', `ไม่มี TTL ของ period '${pd}'`);
  assert.strictEqual(ttlFor('ไม่มีจริง'), CACHE_TTL_DEFAULT);

  console.log('helmetCriteria self-check: all assertions passed');
}

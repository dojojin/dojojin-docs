// ตัวเลขของ "สัปดาห์นี้/เดือนนี้" เก่าไป 30 นาทีไม่เปลี่ยนข้อสรุปอะไรเลย — หนึ่ง read
// ที่เพิ่มมาในล้านกว่า read ไม่ขยับกราฟ · และการ์ดมี "ข้อมูล ณ HH:MM" กำกับอยู่แล้ว
const CACHE_TTL_BY_PERIOD = {
  hour: 20_000, today: 60_000, yesterday: 600_000,
  week: 1_800_000, month: 1_800_000, custom: 300_000,
  // ย้อนหลัง 3/5/7 วันของหน้าอันดับหมวก — เดิมตกไป default 60 วิ ทั้งที่ 6 วันใช้ 11.7 วิ (O5 · 2026-10-03)
  d3: 300_000, d5: 300_000, d7: 300_000,
};
const CACHE_TTL_DEFAULT = 60_000;
const ttlFor = (period) => CACHE_TTL_BY_PERIOD[period] ?? CACHE_TTL_DEFAULT;

function escapeLiteral(v) { return `'${String(v).replace(/'/g, "''")}'`; }

// เงื่อนไข "อ่านป้ายได้ดีพอ" — ต่อท้าย WHERE ได้เลย (ขึ้นต้นด้วย AND)
// prefix = alias ของตาราง license_plates ใน query นั้น ('' ถ้าไม่มี alias)
//
// อ่านผลที่ตัดสินไว้แล้วตอน INSERT ไม่คำนวณอะไรใหม่ ⇒ ตัวเลขของอดีตนิ่งถาวร
// และ query เร็วขึ้นด้วย (ของเดิมเป็น CASE ~140 สาขาที่ Postgres ต้องไล่ทุกแถว)
function evidenceSql(prefix = 'lp') {
  const col = prefix ? `${prefix}.` : '';
  return ` AND ${col}plate_identified`;
}

// ค่าที่ต้องเขียนลงคอลัมน์ plate_identified ตอน INSERT — ผู้เรียกทุกตัวต้องใช้ตัวนี้
// ห้ามเขียนสูตรเอง (มีสี่จุดในระบบที่ INSERT ลง license_plates และเคยพลาดมาแล้ว
// ตอนต่อสาย touchCamera ที่ต่อไม่ครบทุกจุด)
//
// pPlateOk = พารามิเตอร์ boolean ที่ผู้เรียกคำนวณด้วย plateMatches() มาก่อน
// pConf    = พารามิเตอร์ confidence · pCam = พารามิเตอร์ camera_id
// กล้องที่ยังไม่ตั้ง plate_conf_floor (หรือไม่มีแถวใน cameras) ได้ COALESCE เป็น TRUE
// = ไม่กรองด้วย confidence ซึ่งเป็นพฤติกรรมเดิมของเกณฑ์เก่า (ELSE 0) เป๊ะ
// 🔴 ทุกพารามิเตอร์ต้องเป็นของตัวเองและ cast ให้ชัด ห้ามใช้ร่วมกับพารามิเตอร์ของ
// คอลัมน์ใน INSERT เดียวกัน — ใช้ร่วมแล้ว Postgres ตอบ "inconsistent types deduced
// for parameter $n" แล้ว INSERT ล้มทั้งคำสั่ง (เกิดจริง 2026-09-18 02:00-02:10
// ตอน deploy รอบแรก · LPR หยุดบันทึกไป 10 นาที) ผู้เรียกจึงต้องส่งค่าซ้ำเป็น
// พารามิเตอร์ใหม่ ไม่ใช่ชี้ไปที่ $2/$4 ของคอลัมน์
function stampSql(pPlateOk, pConf, pCam) {
  return `(${pPlateOk}::boolean AND COALESCE(${pConf}::real >= `
       + `(SELECT c.plate_conf_floor FROM cameras c WHERE c.id = ${pCam}::varchar), TRUE))`;
}

/** ป้ายอ่านได้ครบรูปแบบไหม — ฝั่ง JS เพื่อส่งเป็นพารามิเตอร์ให้ stampSql() */
function plateMatches(plate) { return PLATE_OK_RE.test(String(plate || '')); }

// เงื่อนไข "เป็นเหตุการณ์ไม่สวมหมวกของรถ 2 ล้อ" — ฐานของตัวเลขทั้งคู่
function baseSql(prefix = 'lp') {
  const col = prefix ? `${prefix}.` : '';
  return `${col}no_helmet AND ${col}vehicle_type = ${escapeLiteral(MOTO_TYPES[0])}`;
}


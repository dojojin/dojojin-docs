//     โค้ดก่อนแก้ 171 วิ · หลังแก้ 162 วิ)
//   ⇒ ทำให้ "เท่ากัน" โดยยกฝั่งที่ถูกกว่า (helmet-top cold 2.4 วิ) ขึ้นมาใช้ตารางนี้แทน

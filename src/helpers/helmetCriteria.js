// 🔴 นโยบาย cache ร่วมของทุกหน้าที่แสดงตัวเลขหมวกนิรภัย
// สองหน้าที่ cache หมดอายุคนละจังหวะ = แสดงภาพถ่ายคนละนาที แล้วเลขไม่ตรงกัน
// วัดจริง 2026-08-23: หน้าอันดับ TTL 120 วิ · หน้าป้ายทะเบียน TTL 600 วิ (เมื่อวาน)
//   ⇒ ต่างกัน 18 แถวบนหน้าจอ ทั้งที่นิยามเดียวกันเป๊ะ (พิสูจน์แล้ว 0 แถวที่ต่างกัน)
